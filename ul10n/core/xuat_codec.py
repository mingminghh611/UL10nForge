"""XUnity.AutoTranslator (XUAT) dictionary codec with strict round-trip validation.

Matches XUnity.AutoTranslator's TextHelper.cs encoding/decoding semantics:
- Escapes '\\' -> '\\\\', '=' -> '\\=', '\\n' -> '\\n', '\\r' -> '\\r', '//' -> '\\/\\/'
- Decodes unescaped '=' separator (max one per line), inline '//' comments,
  '%3D' legacy escape, and '\\uXXXX' sequences.
- Round-trip gate skips lossy patterns (e.g. strings containing '//' or '%3D'
  that cannot round-trip cleanly in XUAT's flat text format).
- Always writes UTF-8 without BOM with `00_` filename prefix so XUAT prioritizes
  our curated dictionary over `_AutoGeneratedTranslations.txt`.
"""
from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from ul10n.core.models import Entry, STATUS_EDITED, STATUS_TRANSLATED

_TEMPLATE_PH_RE = re.compile(r"(\{\d+(?::[^}]+)?\}|%[sdif])")


def encode_xuat_value(text: str) -> str:
    """Encode a single key or value for a XUAT translation file line (lossless via \\uXXXX).

    Uses XUAT TextHelper.cs native escapes:
    - '\\\\' -> '\\\\\\\\', '=' -> '\\\\=', '\\n' -> '\\\\n', '\\r' -> '\\\\r'
    - '//' -> '/\\\\u002f' (prevents inline comment truncation while round-tripping 100% losslessly)
    - '%3D' -> '%\\\\u0033D' (prevents legacy '=' decoding corruption while round-tripping losslessly)
    """
    out: list[str] = []
    i = 0
    n = len(text)
    while i < n:
        ch = text[i]
        if ch == "\\":
            out.append("\\\\")
        elif ch == "=":
            out.append("\\=")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "#" and not "".join(out).strip():
            out.append("\\u0023")
        elif ch == "/" and i + 1 < n and text[i + 1] == "/":
            out.append("/\\u002f")
            i += 1
        elif ch == "%" and i + 2 < n and text[i + 1 : i + 3] == "3D":
            out.append("%\\u0033D")
            i += 2
        else:
            out.append(ch)
        i += 1
    return "".join(out)


def decode_xuat_line(line: str) -> tuple[str, str] | None:
    """Decode one XUAT `key=value` line following TextHelper.ReadTranslationLineAndDecode."""
    if not line:
        return None
    stripped = line.lstrip()
    if not stripped or stripped.startswith("//") or stripped.startswith("#"):
        return None

    key_buf: list[str] = []
    val_buf: list[str] = []
    in_val = False
    i = 0
    n = len(line)

    while i < n:
        ch = line[i]
        if ch == "\\" and i + 1 < n:
            nxt = line[i + 1]
            target = val_buf if in_val else key_buf
            if nxt == "n":
                target.append("\n")
                i += 2
                continue
            if nxt == "r":
                target.append("\r")
                i += 2
                continue
            if nxt == "\\":
                target.append("\\")
                i += 2
                continue
            if nxt == "=":
                target.append("=")
                i += 2
                continue
            if nxt == "u" and i + 5 < n:
                hex_part = line[i + 2 : i + 6]
                try:
                    target.append(chr(int(hex_part, 16)))
                    i += 6
                    continue
                except ValueError:
                    pass
            # Note: XUAT TextHelper default branch keeps unknown escapes (including \/) verbatim!
            target.append("\\")
            target.append(nxt)
            i += 2
            continue

        if ch == "/" and i + 1 < n and line[i + 1] == "/":
            if not in_val:
                return None  # comment inside key invalidates line
            break  # inline comment truncates value

        if ch == "%" and i + 2 < n and line[i + 1 : i + 3] == "3D":
            (val_buf if in_val else key_buf).append("=")
            i += 3
            continue

        if ch == "=":
            if in_val:
                return None  # second unescaped '=' invalidates line
            in_val = True
            i += 1
            continue

        (val_buf if in_val else key_buf).append(ch)
        i += 1

    if not in_val:
        return None
    key = "".join(key_buf)
    val = "".join(val_buf)
    if not key:
        return None
    return key, val


def encode_xuat_entry(original: str, translation: str) -> str | None:
    """Encode `(original, translation)` and verify exact round-trip fidelity."""
    if not original or not translation:
        return None
    # Skip regex/splitter directive prefixes that XUAT interprets specially
    if original.startswith(("r:", "sr:")):
        return None
    line = f"{encode_xuat_value(original)}={encode_xuat_value(translation)}"
    decoded = decode_xuat_line(line)
    if decoded != (original, translation):
        return None
    return line


def parse_xuat_file(path: str | Path) -> list[tuple[str, str]]:
    """Parse a XUAT translation file (UTF-8 / UTF-8-SIG) into `(original, translation)` pairs."""
    p = Path(path)
    if not p.is_file():
        return []
    raw = p.read_text(encoding="utf-8-sig", errors="replace")
    pairs: list[tuple[str, str]] = []
    for line in raw.splitlines():
        decoded = decode_xuat_line(line)
        if decoded is not None:
            pairs.append(decoded)
    return pairs


@dataclass(frozen=True)
class ExportStats:
    path: Path
    exported: int
    skipped_lossy: int
    regex_rules: int = 0


def compile_xuat_regex_entry(original: str, translation: str) -> str | None:
    """Compile a translated placeholder template (e.g. `{0} added to inventory`) into a XUAT `r:` rule.

    Allows dynamic runtime strings like `Bucket of Water added to inventory` or `Wave 12`
    to match offline at 0ms without hitting live AI translation!
    """
    if not original or not translation or "\n" in original or "\n" in translation:
        return None
    if original.startswith(("r:", "sr:")):
        return None
    matches = list(_TEMPLATE_PH_RE.finditer(original))
    if not matches or len(matches) > 3:
        return None
    # Require enough static literal context around placeholders so regex never over-matches
    static_text = _TEMPLATE_PH_RE.sub("", original).strip()
    if len(static_text) < 3 or not any(c.isalpha() for c in static_text):
        return None

    # Build regex pattern and placeholder -> capture group mapping
    parts: list[str] = ["^"]
    pos = 0
    ph_to_group: dict[str, int] = {}
    group_idx = 0
    for m in matches:
        lit = original[pos : m.start()]
        if lit:
            parts.append(re.escape(lit))
        token = m.group(1)
        group_idx += 1
        ph_to_group.setdefault(token, group_idx)
        # Numeric format specifiers match digits; generic placeholders match non-greedy text
        if token in ("%d", "%i") or token.endswith((":0}", ":N0}", ":D}")):
            parts.append(r"(\d+)")
        elif token == "%f":
            parts.append(r"([\d.,]+)")
        else:
            parts.append(r"(.+?)")
        pos = m.end()
    tail = original[pos:]
    if tail:
        parts.append(re.escape(tail))
    parts.append("$")
    pattern = "".join(parts)

    # Reject characters that break XUAT r:"..." parsing
    if '"' in pattern or "=" in pattern or "//" in pattern:
        return None

    # Replace placeholders in translation with XUAT capture refs ($1, $2, ...)
    replaced = translation
    for token, grp in ph_to_group.items():
        if token not in replaced:
            return None
        replaced = replaced.replace(token, f"${grp}")
    # Ensure regex compiles cleanly in Python (validates balanced syntax)
    try:
        re.compile(pattern)
    except re.error:
        return None
    encoded_val = encode_xuat_value(replaced)
    if "//" in encoded_val or "%3D" in encoded_val:
        return None
    return f'r:"{pattern}"={encoded_val}'


def render_xuat_dict_text(
    entries: list[Entry], *, include_regex: bool = False
) -> tuple[str, int, int, int]:
    """Render XUAT curated dictionary text (exact `key=value` pairs; regex rules opt-in only).

    Defaulting `include_regex=False` avoids fragile/slow auto-generated `r:"..."` rules
    and lets XUAT's native matching & live translation handle dynamic strings cleanly.
    Returns `(text, exported_exact, skipped_lossy, regex_rules)`.
    """
    lines: list[str] = [
        "// Generated by UL10nForge v2 — curated high-priority dictionary",
    ]
    regex_lines: list[str] = []
    seen: set[str] = set()
    seen_regex: set[str] = set()
    exported = 0
    skipped_lossy = 0

    for entry in entries:
        if entry.status not in (STATUS_TRANSLATED, STATUS_EDITED):
            continue
        if not entry.translation or entry.original in seen:
            continue
        seen.add(entry.original)
        encoded = encode_xuat_entry(entry.original, entry.translation)
        if encoded is None:
            skipped_lossy += 1
            continue
        lines.append(encoded)
        exported += 1
        if include_regex:
            rx = compile_xuat_regex_entry(entry.original, entry.translation)
            if rx and rx not in seen_regex:
                seen_regex.add(rx)
                regex_lines.append(rx)

    if regex_lines:
        lines.append("")
        lines.append("// Compiled dynamic template regex rules (opt-in)")
        lines.extend(regex_lines)

    if skipped_lossy:
        lines.insert(1, f"// Note: skipped {skipped_lossy} lossy entries incompatible with XUAT flat format")

    return "\n".join(lines) + "\n", exported, skipped_lossy, len(regex_lines)


def export_xuat_file(
    entries: list[Entry], out_path: str | Path, *, include_regex: bool = False
) -> ExportStats:
    """Export publishable translated/edited entries to a UTF-8 (no BOM) XUAT file."""
    target = Path(out_path)
    target.parent.mkdir(parents=True, exist_ok=True)
    text, exported, skipped_lossy, regex_rules = render_xuat_dict_text(
        entries, include_regex=include_regex
    )
    # UTF-8 without BOM (XUAT treats BOM as part of first line's key!)
    target.write_text(text, encoding="utf-8", newline="\n")
    return ExportStats(
        path=target,
        exported=exported,
        skipped_lossy=skipped_lossy,
        regex_rules=regex_rules,
    )


def prune_xuat_auto_file(auto_path: str | Path, managed_originals: set[str]) -> int:
    """Remove keys already managed in `00_UL10nForge.txt` (or skipped) from `_AutoGeneratedTranslations.txt`.

    Prevents stale auto-generated translations from shadowing user edits or skipped entries
    when XUnity.AutoTranslator hot-reloads translation files alphabetically.
    """
    p = Path(auto_path)
    if not managed_originals or not p.is_file():
        return 0
    try:
        raw = p.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return 0
    if not raw.strip():
        return 0

    kept: list[str] = []
    removed = 0
    for line in raw.splitlines():
        decoded = decode_xuat_line(line)
        if decoded is not None and decoded[0] in managed_originals:
            removed += 1
            continue
        kept.append(line)

    if removed > 0:
        new_text = ("\n".join(kept) + "\n") if kept else ""
        try:
            p.write_text(new_text, encoding="utf-8", newline="\n")
        except OSError:
            return 0
    return removed
